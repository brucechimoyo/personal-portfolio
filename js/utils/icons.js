/* Pick an icon for a social link from its name or URL */
export function socialIcon(link = {}, size = 18) {
  const key = `${link.name || ''} ${link.url || ''}`.toLowerCase();
  if (key.includes('github')) return icon('github', size);
  if (key.includes('linkedin')) return icon('linkedin', size);
  if (key.includes('twitter') || key.includes('x.com')) return icon('twitter', size);
  if (key.includes('medium')) return icon('medium', size);
  if (key.includes('mailto') || key.includes('email')) return icon('mail', size);
  return icon('link', size);
}
